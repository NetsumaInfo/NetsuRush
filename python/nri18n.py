def language():
    """Interface language from `NR_LANG`; French when unset (the core's default), English for a
    language the table does not carry."""
    code = (os.environ.get("NR_LANG") or "fr").lower().replace("_", "-").split("-", 1)[0]
    return code if code in LANGS else "en"


def t(key, **values):
    """Message `key` in the interface language, `{placeholders}` filled from `values`."""
    row = _MESSAGES.get(key)
    if row is None:
        return key
    return row[LANGS.index(language())].format(**values)
